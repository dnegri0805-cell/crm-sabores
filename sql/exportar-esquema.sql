-- ============================================================
-- EXPORTAR ESQUEMA COMPLETO (solo lectura, no cambia nada)
-- Pegalo en Supabase → SQL Editor → Run.
-- Devuelve UNA fila con toda la estructura de la base (tipos,
-- tablas, vistas, funciones, índices, triggers, permisos, RLS y
-- carpetas de archivos) de los esquemas public y private, más
-- los triggers propios sobre auth.users.
-- El resultado se guarda como sql/00-esquema-completo.sql.
-- No exporta datos de clientes: solo la estructura.
-- ============================================================
with recursive
esq as (
  select n.oid, n.nspname from pg_namespace n where n.nspname in ('public', 'private')
),
-- Orden de las vistas: primero las que no dependen de otras vistas
vdep as (
  select distinct r.ev_class as v, d.refobjid as w
  from pg_rewrite r
  join pg_depend d on d.classid = 'pg_rewrite'::regclass and d.objid = r.oid
  join pg_class w on w.oid = d.refobjid and w.relkind in ('v','m')
  where d.refobjid <> r.ev_class
),
vniv as (
  select c.oid as v, 0 as n from pg_class c join esq e on e.oid = c.relnamespace where c.relkind in ('v','m')
  union all
  select vd.v, vn.n + 1 from vniv vn join vdep vd on vd.w = vn.v where vn.n < 50
),
vorden as (
  select v, max(n) as n from vniv group by v
),
ext as (
  select 0 as o, 'create extension if not exists ' || quote_ident(e.extname)
    || ' with schema ' || quote_ident(n.nspname) || ';' as l, null::text as k
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname in ('pgcrypto', 'uuid-ossp', 'pg_trgm', 'unaccent', 'citext', 'pg_net', 'pg_cron')
),
schemas as (
  select 0 as o, 'create schema if not exists ' || quote_ident(nspname) || ';' as l, null::text as k
  from esq where nspname <> 'public'
),
enums as (
  select 1 as o, 'create type ' || quote_ident(e.nspname) || '.' || quote_ident(t.typname) || ' as enum ('
    || string_agg(quote_literal(en.enumlabel), ', ' order by en.enumsortorder) || ');' as l, null::text as k
  from pg_type t join esq e on e.oid = t.typnamespace
  join pg_enum en on en.enumtypid = t.oid
  where t.typtype = 'e'
  group by e.nspname, t.typname
),
doms as (
  select 1 as o, 'create domain ' || quote_ident(e.nspname) || '.' || quote_ident(t.typname) || ' as '
    || format_type(t.typbasetype, t.typtypmod)
    || coalesce(' default ' || t.typdefault, '') || case when t.typnotnull then ' not null' else '' end
    || coalesce((select ' ' || string_agg(pg_get_constraintdef(c.oid), ' ') from pg_constraint c where c.contypid = t.oid), '')
    || ';' as l, null::text as k
  from pg_type t join esq e on e.oid = t.typnamespace
  where t.typtype = 'd'
),
seqs as (
  select 2 as o, 'create sequence if not exists ' || quote_ident(e.nspname) || '.' || quote_ident(c.relname) || ';' as l, null::text as k
  from pg_class c join esq e on e.oid = c.relnamespace
  where c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
tabs as (
  select 3 as o,
    'create table if not exists ' || quote_ident(e.nspname) || '.' || quote_ident(c.relname) || ' (' || E'\n' ||
    string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case when a.attidentity = 'a' then ' generated always as identity'
              when a.attidentity = 'd' then ' generated by default as identity' else '' end
      || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
              when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
      || case when a.attnotnull then ' not null' else '' end,
      ',' || E'\n' order by a.attnum) || E'\n);' as l, null::text as k
  from pg_class c
  join esq e on e.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
  where c.relkind in ('r','p')
  group by e.nspname, c.relname
),
seqown as (
  select 4 as o, 'alter sequence ' || quote_ident(e.nspname) || '.' || quote_ident(s.relname) || ' owned by '
    || quote_ident(e.nspname) || '.' || quote_ident(t.relname) || '.' || quote_ident(a.attname) || ';' as l, null::text as k
  from pg_depend d
  join pg_class s on s.oid = d.objid and s.relkind = 'S'
  join pg_class t on t.oid = d.refobjid
  join esq e on e.oid = t.relnamespace
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where d.deptype = 'a'
),
cons as (
  select case when con.contype = 'f' then 6 else 5 end as o,
    'alter table ' || quote_ident(e.nspname) || '.' || quote_ident(c.relname) || ' add constraint ' || quote_ident(con.conname)
    || ' ' || pg_get_constraintdef(con.oid) || ';' as l, null::text as k
  from pg_constraint con
  join pg_class c on c.oid = con.conrelid
  join esq e on e.oid = c.relnamespace
  where con.contype in ('p','u','c','f','x')
),
idx as (
  select 7 as o, i.indexdef || ';' as l, null::text as k
  from pg_indexes i
  where i.schemaname in (select nspname from esq)
    and not exists (select 1 from pg_constraint con join pg_namespace n on n.oid = con.connamespace
                    where con.conname = i.indexname and n.nspname = i.schemaname)
),
-- Las funciones van antes que las tablas (hay tablas que las usan como valor por defecto),
-- salvo las que reciben o devuelven el tipo de una tabla, que van después.
funcs as (
  select case when exists (
           select 1 from pg_type t
           where t.oid = any(array_append(coalesce(p.proallargtypes, p.proargtypes::oid[]), p.prorettype))
             and t.typrelid <> 0
             and exists (select 1 from pg_class rc where rc.oid = t.typrelid and rc.relkind in ('r','p','v','m'))
         ) then 8 else 2 end as o,
    pg_get_functiondef(p.oid) || ';' as l, null::text as k
  from pg_proc p join esq e on e.oid = p.pronamespace
  where p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
views as (
  select 9 as o, 'create or replace view ' || quote_ident(e.nspname) || '.' || quote_ident(c.relname)
    || coalesce(' with (' || array_to_string(c.reloptions, ', ') || ')', '')
    || ' as' || E'\n' || rtrim(pg_get_viewdef(c.oid, true), ';') || ';' as l, lpad(vo.n::text, 4, '0') || c.relname as k
  from pg_class c join esq e on e.oid = c.relnamespace join vorden vo on vo.v = c.oid
  where c.relkind = 'v'
),
mviews as (
  select 9 as o, 'create materialized view if not exists ' || quote_ident(e.nspname) || '.' || quote_ident(c.relname)
    || ' as' || E'\n' || rtrim(pg_get_viewdef(c.oid, true), ';') || ';' as l, lpad(vo.n::text, 4, '0') || c.relname as k
  from pg_class c join esq e on e.oid = c.relnamespace join vorden vo on vo.v = c.oid
  where c.relkind = 'm'
),
trig as (
  select 10 as o, pg_get_triggerdef(t.oid) || ';' as l, null::text as k
  from pg_trigger t join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_proc p on p.oid = t.tgfoid
  where not t.tgisinternal
    and (n.nspname in (select nspname from esq)
         or (n.nspname = 'auth' and p.pronamespace in (select oid from esq)))
),
rls as (
  select 11 as o, 'alter table ' || quote_ident(e.nspname) || '.' || quote_ident(c.relname) || ' enable row level security;' as l, null::text as k
  from pg_class c join esq e on e.oid = c.relnamespace
  where c.relkind in ('r','p') and c.relrowsecurity
),
pol as (
  select 12 as o,
    'create policy ' || quote_ident(p.policyname) || ' on ' || quote_ident(p.schemaname) || '.' || quote_ident(p.tablename)
    || ' as ' || lower(p.permissive) || ' for ' || lower(p.cmd)
    || ' to ' || array_to_string(p.roles, ', ')
    || coalesce(' using (' || p.qual || ')', '')
    || coalesce(' with check (' || p.with_check || ')', '') || ';' as l, null::text as k
  from pg_policies p where p.schemaname in (select nspname from esq)
),
fgrants as (
  select 13 as o, 'grant execute on function ' || quote_ident(e.nspname) || '.' || quote_ident(p.proname)
    || '(' || pg_get_function_identity_arguments(p.oid) || ') to ' || r.rolname || ';' as l, null::text as k
  from pg_proc p
  join esq e on e.oid = p.pronamespace
  cross join lateral aclexplode(p.proacl) ax
  join pg_roles r on r.oid = ax.grantee
  where r.rolname in ('anon','authenticated','service_role') and ax.privilege_type = 'EXECUTE'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
buckets as (
  select 14 as o, 'insert into storage.buckets (id, name, public) values ('
    || quote_literal(b.id) || ', ' || quote_literal(b.name) || ', ' || b.public
    || ') on conflict (id) do nothing;' as l, null::text as k
  from storage.buckets b
),
spol as (
  select 15 as o,
    'create policy ' || quote_ident(p.policyname) || ' on storage.objects'
    || ' as ' || lower(p.permissive) || ' for ' || lower(p.cmd)
    || ' to ' || array_to_string(p.roles, ', ')
    || coalesce(' using (' || p.qual || ')', '')
    || coalesce(' with check (' || p.with_check || ')', '') || ';' as l, null::text as k
  from pg_policies p where p.schemaname = 'storage' and p.tablename = 'objects'
),
todo as (
  select * from ext union all select * from schemas union all select * from enums
  union all select * from doms union all select * from seqs union all select * from tabs
  union all select * from seqown union all select * from cons union all select * from idx
  union all select * from funcs union all select * from views union all select * from mviews
  union all select * from trig union all select * from rls union all select * from pol
  union all select * from fgrants union all select * from buckets union all select * from spol
)
select
  '-- Esquema completo de la base del CRM Sabores de mi País' || E'\n' ||
  '-- Exportado el ' || to_char(now() at time zone 'America/Argentina/Buenos_Aires', 'DD/MM/YYYY') || E'\n' ||
  '-- Solo estructura, sin datos. Para recrear la base en un proyecto nuevo de Supabase:' || E'\n' ||
  '-- pegar todo en SQL Editor → Run (con el proyecto nuevo vacío).' || E'\n\n' ||
  'set check_function_bodies = off;' || E'\n\n' ||
  string_agg(l, E'\n\n' order by o, coalesce(k, l)) as esquema
from todo;
