-- ============================================================
-- EXPORTAR ESQUEMA COMPLETO (solo lectura, no cambia nada)
-- Pegalo en Supabase → SQL Editor → Run.
-- Devuelve UNA fila con todo el esquema de la base (tablas,
-- vistas, funciones, índices, triggers, permisos y RLS) listo
-- para guardarlo como sql/00-esquema-completo.sql en el repo.
-- No exporta datos de clientes: solo la estructura.
-- ============================================================
with
seqs as (
  select 1 as o, 'create sequence if not exists public.' || quote_ident(c.relname) || ';' as l, null::text as k
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
tabs as (
  select 2 as o,
    'create table if not exists public.' || quote_ident(c.relname) || ' (' || E'\n' ||
    string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case when a.attidentity = 'a' then ' generated always as identity'
              when a.attidentity = 'd' then ' generated by default as identity' else '' end
      || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
              when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
      || case when a.attnotnull then ' not null' else '' end,
      ',' || E'\n' order by a.attnum) || E'\n);' as l, null::text as k
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
  where n.nspname = 'public' and c.relkind in ('r','p')
  group by c.relname
),
seqown as (
  select 3 as o, 'alter sequence public.' || quote_ident(s.relname) || ' owned by public.'
    || quote_ident(t.relname) || '.' || quote_ident(a.attname) || ';' as l, null::text as k
  from pg_depend d
  join pg_class s on s.oid = d.objid and s.relkind = 'S'
  join pg_class t on t.oid = d.refobjid
  join pg_namespace n on n.oid = t.relnamespace and n.nspname = 'public'
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where d.deptype = 'a'
),
cons as (
  select case when con.contype = 'f' then 5 else 4 end as o,
    'alter table public.' || quote_ident(c.relname) || ' add constraint ' || quote_ident(con.conname)
    || ' ' || pg_get_constraintdef(con.oid) || ';' as l, null::text as k
  from pg_constraint con
  join pg_class c on c.oid = con.conrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and con.contype in ('p','u','c','f','x')
),
idx as (
  select 6 as o, i.indexdef || ';' as l, null::text as k
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint con where con.conname = i.indexname
                    and con.connamespace = 'public'::regnamespace)
),
funcs as (
  select 7 as o, pg_get_functiondef(p.oid) || ';' as l, null::text as k
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
views as (
  select 8 as o, 'create or replace view public.' || quote_ident(c.relname)
    || coalesce(' with (' || array_to_string(c.reloptions, ', ') || ')', '')
    || ' as' || E'\n' || pg_get_viewdef(c.oid, true) || ';' as l, lpad(c.oid::text, 12, '0') as k
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
mviews as (
  select 8 as o, 'create materialized view if not exists public.' || quote_ident(c.relname)
    || ' as' || E'\n' || pg_get_viewdef(c.oid, true) || ';' as l, lpad(c.oid::text, 12, '0') as k
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'm'
),
trig as (
  select 9 as o, pg_get_triggerdef(t.oid) || ';' as l, null::text as k
  from pg_trigger t join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and not t.tgisinternal
),
rls as (
  select 10 as o, 'alter table public.' || quote_ident(c.relname) || ' enable row level security;' as l, null::text as k
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p') and c.relrowsecurity
),
pol as (
  select 11 as o,
    'create policy ' || quote_ident(p.policyname) || ' on public.' || quote_ident(p.tablename)
    || ' as ' || lower(p.permissive) || ' for ' || lower(p.cmd)
    || ' to ' || array_to_string(p.roles, ', ')
    || coalesce(' using (' || p.qual || ')', '')
    || coalesce(' with check (' || p.with_check || ')', '') || ';' as l, null::text as k
  from pg_policies p where p.schemaname = 'public'
),
fgrants as (
  select 12 as o, 'grant execute on function public.' || quote_ident(p.proname)
    || '(' || pg_get_function_identity_arguments(p.oid) || ') to ' || r.rolname || ';' as l, null::text as k
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace and n.nspname = 'public'
  cross join lateral aclexplode(p.proacl) ax
  join pg_roles r on r.oid = ax.grantee
  where r.rolname in ('anon','authenticated','service_role') and ax.privilege_type = 'EXECUTE'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
buckets as (
  select 13 as o, 'insert into storage.buckets (id, name, public) values ('
    || quote_literal(b.id) || ', ' || quote_literal(b.name) || ', ' || b.public
    || ') on conflict (id) do nothing;' as l, null::text as k
  from storage.buckets b
),
spol as (
  select 14 as o,
    'create policy ' || quote_ident(p.policyname) || ' on storage.objects'
    || ' as ' || lower(p.permissive) || ' for ' || lower(p.cmd)
    || ' to ' || array_to_string(p.roles, ', ')
    || coalesce(' using (' || p.qual || ')', '')
    || coalesce(' with check (' || p.with_check || ')', '') || ';' as l, null::text as k
  from pg_policies p where p.schemaname = 'storage' and p.tablename = 'objects'
),
todo as (
  select * from seqs union all select * from tabs union all select * from seqown
  union all select * from cons union all select * from idx union all select * from funcs
  union all select * from views union all select * from mviews union all select * from trig
  union all select * from rls union all select * from pol union all select * from fgrants
  union all select * from buckets union all select * from spol
)
select
  '-- Esquema completo de la base del CRM Sabores de mi País' || E'\n' ||
  '-- Exportado el ' || to_char(now() at time zone 'America/Argentina/Buenos_Aires', 'DD/MM/YYYY HH24:MI') || E'\n' ||
  '-- Solo estructura, sin datos. Para recrear la base en un proyecto nuevo de Supabase.' || E'\n\n' ||
  'set check_function_bodies = off;' || E'\n\n' ||
  string_agg(l, E'\n\n' order by o, coalesce(k, l)) as esquema
from todo;
